"""Reproduce the single-file proof and its declaration audit from local sources."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
VERIFY = ROOT / "verification"
MODULES = {
    "Erdos302." + path.stem: path
    for path in sorted((ROOT / "Erdos302").glob("*.lean"))
}
MODULES["verification.StatementCheck"] = VERIFY / "StatementCheck.lean"
ORDER: list[str] = []
VISITING: set[str] = set()


def visit(name: str) -> None:
    if name in ORDER:
        return
    if name in VISITING:
        raise RuntimeError("Import cycle at " + name)
    VISITING.add(name)
    for imported in re.findall(r"^import (\S+)\s*$", MODULES[name].read_text(encoding="utf-8"), re.M):
        if imported in MODULES:
            visit(imported)
    VISITING.remove(name)
    ORDER.append(name)


for module in MODULES:
    visit(module)

external_imports: set[str] = set()
parts: list[str] = []
sources: list[dict] = []
targets: list[dict] = []
conditional_removal = {
    "Erdos302.uniform_approximation_of_removal",
    "Erdos302.densityLimit_of_removal",
    "Erdos302.limiting_removal_bound",
    "Erdos302.effectiveApproximation_of_removal",
}

for module in ORDER:
    path = MODULES[module]
    source = path.read_text(encoding="utf-8")
    relative = path.relative_to(ROOT).as_posix()
    sources.append({"path": relative, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    lines: list[str] = []
    namespace: list[str] = []
    for line in source.splitlines():
        imported = re.fullmatch(r"import (\S+)\s*", line)
        if imported:
            name = imported.group(1)
            if name not in MODULES and name != "Erdos302":
                external_imports.add(name)
            continue
        lines.append(line)
        opened = re.fullmatch(r"namespace (\S+)\s*", line)
        if opened:
            namespace.append(opened.group(1))
        elif re.fullmatch(r"end(?: \S+)?\s*", line):
            if not namespace:
                raise RuntimeError("Unexpected namespace end in " + relative)
            namespace.pop()
        declaration = re.match(r"^(?:theorem|lemma) ([\w']+)", line)
        if declaration:
            name = ".".join(namespace + [declaration.group(1)])
            target = {"name": name, "path": relative, "assumes_removal": name in conditional_removal}
            if name == "Erdos302.removalEstimate_of_largeRegular_bound":
                target["assumes_large_regular_bound"] = True
            targets.append(target)
    if namespace:
        raise RuntimeError("Unclosed namespace in " + relative)
    parts.append("-- Source " + relative + "\n" + "\n".join(lines).strip() + "\n")

header = "\n".join("import " + name for name in sorted(external_imports))
header += "\n\n/-!\nPrivate single-file proof of the Erdős 302 density limit and explicit removal estimates.\n"
header += "Generated by verification/prepare_full_verification.py from the accompanying modules.\n"
header += "The mathematical source attribution is recorded in verification/REPORT.md.\n"
header += "Lean 4.34.0, mathlib 5ed2965256430c3649e86755f9576b54eca72435.\n-/\n\n"
bundle = ROOT / "Erdos302Full.lean"
bundle.write_text(header + "\n".join(parts), encoding="utf-8", newline="\n")
manifest = {
    "output": bundle.name,
    "sha256": hashlib.sha256(bundle.read_bytes()).hexdigest(),
    "source_order": sources,
    "external_imports": sorted(external_imports),
}
(VERIFY / "BUNDLE_MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

required = [
    "Erdos302.fixedPrimeLimit", "Erdos302.removalEstimate", "Erdos302.densityLimit",
    "Erdos302.effectiveApproximation", "Erdos302.uniform_finite_removal_rate",
    "Erdos302.rational_enclosures", "OriginalStatementCheck.full_density_as_stated",
    "OriginalStatementCheck.full_removal_as_stated", "OriginalStatementCheck.full_effective_rate_as_stated",
    "OriginalStatementCheck.full_rational_enclosures_as_stated",
    "Erdos302.density_not_one_half", "OriginalStatementCheck.original_half_question_as_stated",
]
names = [t["name"] for t in targets]
if len(set(names)) != len(names) or not set(required) <= set(names):
    raise RuntimeError("Incomplete or duplicate declaration registry")
registry = {
    "goal": "Full density limit, explicit removal estimates, and finite rational enclosures",
    "registry_kind": "proof_declarations",
    "unproved_central_requirement": None,
    "remaining_analytic_requirement": None,
    "required_full_targets": required,
    "targets": targets,
}
(VERIFY / "current-targets.json").write_text(json.dumps(registry, indent=2) + "\n", encoding="utf-8")
commands = "\n".join("#check " + n + "\n#print axioms " + n + "\n" for n in names)
(VERIFY / "CurrentAudit.lean").write_text(
    "import Erdos302\nimport verification.StatementCheck\nset_option pp.proofs false\n\n" + commands,
    encoding="utf-8",
)
(VERIFY / "FullAudit.lean").write_text(
    "import Erdos302Full\nset_option pp.proofs false\n\n" + commands, encoding="utf-8",
)
print(json.dumps({"source_modules": len(sources), "declarations": len(targets),
                  "bundle_sha256": manifest["sha256"]}))
